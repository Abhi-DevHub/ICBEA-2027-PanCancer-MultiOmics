def build_class_mapping(omics_combined, labels):
    """Data-driven class 0-31 -> TCGA project code -> cancer name.

    Labels have no name mapping in the repo, but every sample id is a TCGA barcode,
    so the tissue-source-site code (and from it the project) is recoverable from the
    sample index.
    """
    rows = []
    for cls in sorted(labels.unique()):
        idx = labels[labels == cls].index
        codes = [tcga_project_code(s) for s in idx]
        dominant = max(set(codes), key=codes.count)
        project = TSS_PROJECT.get(dominant, "UNKNOWN")
        rows.append({
            "class": int(cls),
            "n_samples": len(idx),
            "dominant_tss_code": dominant,
            "tcga_code": project,
            "cancer_name": TCGA_PROJECT_NAMES.get(project, "Unknown"),
            "codes_present": sorted(set(codes)),
        })
    return pd.DataFrame(rows)